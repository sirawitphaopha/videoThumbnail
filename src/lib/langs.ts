const ALIAS: Record<string, string> = { zho: "chi", deu: "ger", fra: "fre", nld: "dut", ces: "cze", slk: "slo", ron: "rum", ell: "gre", fas: "per", isl: "ice", cym: "wel", eus: "baq", kat: "geo", hye: "arm", mkd: "mac", sqi: "alb", mya: "bur", msa: "may", bod: "tib" };
for (const l of LANG_ALL) if (l[3]) ALIAS[l[3]] = l[2];

export function langOf(code: string | null | undefined): Lang {
  const c = (code ?? "und").toLowerCase();
  return BY.get(c) ?? BY.get(ALIAS[c] ?? "") ?? LANG_UND;
}
/** ชื่อที่แสดงในช่องภาษา · ไทยก่อน ไม่มีใช้ชื่ออังกฤษ */
export function langName(code: string | null | undefined): string {
  const l = langOf(code);
  return l[0] || l[1];
}
/** ป้ายรหัส แบบ th · tha */
export function langCode(l: Lang): string {
  return l[3] ? `${l[3]}, ${l[2]}` : l[2];
}
