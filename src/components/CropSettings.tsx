import { useSettings } from "../lib/settings";
import { Switch } from "./ui";
import InfoTip from "./InfoTip";

export default function CropSettings() {
  const { settings, update } = useSettings();
  if (!settings) return null;
  return (
    <div className="cropshrink" data-crop-shrink>
      <Switch on={settings.shrinkLargePosters} onChange={(v) => void update({ shrinkLargePosters: v })} label="ย่อรูปโปสเตอร์ที่ใหญ่เกิน 1000 × 1500 px" />
      {/* ชื่อเดียวกับสวิตช์ในหน้าตั้งค่า หัวข้อรูปโปสเตอร์ คนเห็นแล้วรู้ว่าเป็นตัวเดียวกัน (BUGS ข้อ 55 ต่อ พี่กัน "จุดนี้ ใส่ในตั้งค่าด้วย") */}
      <span>ย่อรูปโปสเตอร์ที่ใหญ่เกิน <span className="nw">1000 × 1500 px</span></span>
      <InfoTip title="ย่อรูปโปสเตอร์ที่ใหญ่เกินคืออะไร" tip={{ w: "เปิดไว้ รูปที่ใหญ่กว่า 1000 × 1500 px ถูกย่อลงเหลือ 1000 × 1500 px ก่อนแนบ ไฟล์หนังไม่บวม เช่นรูป 4000 × 6000 px หลาย MB เหลือราว 100 ถึง 300 KB ชั้นวางกับโปรแกรมเล่นแสดงปกเล็กกว่านี้อยู่แล้ว จึงมองไม่เห็นความต่าง ปิดไว้ เก็บความละเอียดเดิมได้ถึง 6000 px สำหรับคนที่อยากได้ปกคมเต็มที่ ค่านี้เป็นค่าเดียวกับสวิตช์ในหน้าตั้งค่า หัวข้อรูปโปสเตอร์ ปรับที่ไหนอีกที่ก็เปลี่ยนตาม" }} />
    </div>
  );
}
