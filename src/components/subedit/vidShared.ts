/** ข้อความที่ตาเห็นบนภาพ ไม่มีแท็ก ขึ้นบรรทัดจริง */
export function shownText(e: SubEvent, d: SubDoc) {
  return isAss(d) ? e.text.replace(/\{[^}]*\}/g, "").replace(/\\[Nn]/g, "\n").replace(/\\h/g, " ") : e.text.replace(/<[^>]*>/g, "");
}

